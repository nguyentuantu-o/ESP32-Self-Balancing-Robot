#pragma once

// Intermediate measurements and outputs from the encoder control loop.
struct SpeedData {
    float leftRawRPM;
    float rightRawRPM;
    float speedRPM;          // Filtered average speed of both wheels
    float targetRPM;         // Speed target generated by the position loop
    float positionErrorRev;  // Filtered position error, in wheel revolutions
    float speedErrorRPM;     // Filtered speed error
    float targetRoll;        // Roll offset generated by the speed PI loop
};

// Set the initial encoder reference and initialize the outer loop.
void speedControlInit();

// Clear loop errors/integrators and use the current wheel positions as the reference.
void resetSpeedController();

// Update the position/speed loops at the encoder sample rate and return the latest roll offset.
SpeedData updateSpeedLoop(unsigned long nowUs, bool enabled);